var points = ee.FeatureCollection(PTS.map(function (r) {
  return ee.Feature(ee.Geometry.Point([r[2], r[3]]),
                    {PointID: r[0], Original_ID: r[1], lon: r[2], lat: r[3]});
}));
print('n points (expect 150):', points.size());

// ---- Dynamic World: 2021 annual majority label --------------------------
// label: 0 water,1 trees,2 grass,3 flooded_veg,4 crops,5 shrub,6 built,7 bare,8 snow/ice
var dwRaw = ee.ImageCollection('GOOGLE/DYNAMICWORLD/V1')
  .filterBounds(points).filterDate(YEAR_START, YEAR_END)
  .select('label').mode().rename('DW_raw');

// ---- ESRI / Impact Observatory Land Cover, 2021 ------------------------
// values 1..11: 1 water,2 trees,4 flooded_veg,5 crops,7 built,8 bare,9 snow,10 cloud,11 rangeland
var esriRaw = ee.ImageCollection(
    'projects/sat-io/open-datasets/landcover/ESRI_Global-LULC_10m_TS')
  .filterDate(YEAR_START, YEAR_END).mosaic().rename('ESRI_raw');

// ---- ESA WorldCover v200 (2021) ---------------------------------------
var wcRaw = ee.ImageCollection('ESA/WorldCover/v200').first()
  .select('Map').rename('WC_ee_raw');

var stack = dwRaw.toInt16().addBands(esriRaw.toInt16()).addBands(wcRaw.toInt16());

var sampled = stack.reduceRegions({
  collection: points, reducer: ee.Reducer.first(), scale: 10, tileScale: 4
});

print('first 5 sampled:', sampled.limit(5));
Map.setOptions('HYBRID');
Map.centerObject(points, 11);
Map.addLayer(points, {color: 'red'}, 'Hangzhou two-stage BAMS150');
Map.addLayer(dwRaw, {min: 0, max: 8}, 'DW label 2021 mode', false);

Export.table.toDrive({
  collection: sampled,
  description: 'Hangzhou_BAMS150_dwesri_raw',
  fileNamePrefix: 'Hangzhou_BAMS150_dwesri_raw',
  fileFormat: 'CSV',
  selectors: ['PointID', 'Original_ID', 'lon', 'lat', 'DW_raw', 'ESRI_raw', 'WC_ee_raw']
});
